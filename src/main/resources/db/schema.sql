-- AquaMeter - schema para Oracle Database 23ai (Free / Autonomous Database)
-- Usa recursos do 23ai: CREATE ... IF NOT EXISTS, tipo BOOLEAN nativo e colunas IDENTITY.
-- O script é idempotente: pode rodar a cada inicialização da aplicação.

CREATE TABLE IF NOT EXISTS propriedade (
    id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome                VARCHAR2(120) NOT NULL,
    produtor            VARCHAR2(120) NOT NULL,
    municipio           VARCHAR2(80)  NOT NULL,
    uf                  CHAR(2)       NOT NULL,
    area_ha             NUMBER(10,2)  NOT NULL,
    cultura_principal   VARCHAR2(60),
    tarifa_agua_m3      NUMBER(10,4)  DEFAULT 0 NOT NULL,
    tarifa_energia_kwh  NUMBER(10,4)  DEFAULT 0 NOT NULL,
    criado_em           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS medidor (
    id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    propriedade_id  NUMBER        NOT NULL REFERENCES propriedade(id),
    nome            VARCHAR2(120) NOT NULL,
    tipo            VARCHAR2(10)  NOT NULL CHECK (tipo IN ('AGUA', 'ENERGIA')),
    setor           VARCHAR2(80),
    unidade         VARCHAR2(10)  NOT NULL,
    limite_diario   NUMBER(12,3)  NOT NULL,
    ativo           BOOLEAN       DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS leitura (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    medidor_id  NUMBER        NOT NULL REFERENCES medidor(id),
    data_hora   TIMESTAMP     NOT NULL,
    valor       NUMBER(12,3)  NOT NULL CHECK (valor >= 0)
);

CREATE INDEX IF NOT EXISTS ix_leitura_medidor_data ON leitura (medidor_id, data_hora);

CREATE TABLE IF NOT EXISTS alerta (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    medidor_id  NUMBER         NOT NULL REFERENCES medidor(id),
    data_hora   TIMESTAMP      NOT NULL,
    tipo        VARCHAR2(30)   NOT NULL,
    mensagem    VARCHAR2(400)  NOT NULL,
    valor       NUMBER(12,3),
    limite      NUMBER(12,3),
    resolvido   BOOLEAN        DEFAULT FALSE NOT NULL
);

CREATE TABLE IF NOT EXISTS insumo_aplicacao (
    id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    propriedade_id  NUMBER        NOT NULL REFERENCES propriedade(id),
    data_aplicacao  DATE          NOT NULL,
    insumo          VARCHAR2(120) NOT NULL,
    categoria       VARCHAR2(20)  NOT NULL CHECK (categoria IN ('FERTILIZANTE', 'DEFENSIVO', 'SEMENTE', 'COMBUSTIVEL', 'OUTRO')),
    quantidade      NUMBER(12,3)  NOT NULL,
    unidade         VARCHAR2(10)  NOT NULL,
    custo_total     NUMBER(12,2)  NOT NULL,
    setor           VARCHAR2(80)
);

-- Consolidação diária do consumo, consultada pelo dashboard
CREATE OR REPLACE VIEW vw_consumo_diario AS
SELECT l.medidor_id,
       TRUNC(l.data_hora) AS dia,
       SUM(l.valor)       AS total
  FROM leitura l
 GROUP BY l.medidor_id, TRUNC(l.data_hora);
